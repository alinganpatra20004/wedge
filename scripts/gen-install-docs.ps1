# Writes docs/install/<platform>.md and docs/install/README.md from
# docs/install/source.json (the steps) and docs/install/tested.json (results
# of scripts/test-install.ps1). Edit the source, not the generated pages.
#
# Usage: pwsh scripts/gen-install-docs.ps1
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path $PSScriptRoot -Parent)

$source = Get-Content docs/install/source.json -Raw | ConvertFrom-Json
$tested = if (Test-Path docs/install/tested.json) {
    Get-Content docs/install/tested.json -Raw | ConvertFrom-Json
} else { [pscustomobject]@{} }
$version = (Select-String -Path Cargo.toml -Pattern '^version = "(.+)"' |
    Select-Object -First 1).Matches[0].Groups[1].Value
$base = $source.base_url
$header = "<!-- SPDX-License-Identifier: Apache-2.0 -->`n<!-- Copyright (c) Alingan Patra -->`n" +
    "<!-- Generated by scripts/gen-install-docs.ps1 from docs/install/source.json. Do not edit. -->`n"

function Get-Status($p) {
    if ($p.tested -eq 'ci-runner') {
        return 'Untested on a real machine. The MSI is tested on a GitHub-hosted Windows Server ' +
            'runner by `scripts/test-msi.ps1` in every release build (silent install, service start, ' +
            'HTTP check, uninstall); a Windows 10/11 desktop or VM run is still to be confirmed.'
    }
    if ($p.tested -eq 'untested') {
        return 'Untested: these steps have not yet been run on a clean machine or VM.'
    }
    $r = $tested.($p.id)
    if (-not $r) { return 'Not yet tested.' }
    $what = if ($r.result -eq 'passed') { 'Tested' } else { 'FAILED' }
    "$what on $($r.date) with wedge $($r.version) in a clean ``$($p.image)`` container " +
    "($($r.image)) by ``scripts/test-install.ps1``. The service-manager step is not run " +
    'there (containers have no init system); wedge runs as the `wedge` user instead.'
}

# A fenced PowerShell block from a list of lines. (Building it with `"a" + "b"`
# inside a `,` list would split it: the comma binds tighter than `+`.)
function Get-PsBlock([string[]]$lines) {
    "``````powershell`n$($lines -join "`n")`n``````"
}

function Get-Block([string]$code) {
    "``````sh`n$($code.Trim())`n``````"
}

$pages = @()
foreach ($p in $source.platforms) {
    $asset = $p.asset
    $md = @($header, "# Install wedge on $($p.title)", '', "> $(Get-Status $p)", '')
    switch ($p.kind) {
        { $_ -in 'deb', 'rpm', 'tarball' } {
            $md += '## 1. Prerequisites', '', (Get-Block $p.prerequisites), ''
            $md += '## 2. Download and verify', '',
                'Download the package and the checksum list from the GitHub release, and check the',
                'package before installing it. Never pipe a download straight into a shell.', '',
                (Get-Block "VERSION=$version`nBASE=$base`ncurl -fLO `"`$BASE/$asset`"`ncurl -fLO `"`$BASE/SHA256SUMS`"`ngrep `" $asset`$`" SHA256SUMS | sha256sum -c -"), '',
                'The command must print `OK`. You can also check the build provenance:', '',
                (Get-Block "gh attestation verify $asset --repo alinganpatra20004/wedge"), ''
            $md += '## 3. Install', '', (Get-Block $p.install), ''
            if ($p.kind -ne 'tarball') {
                $md += 'The package creates the `wedge` system user (no login shell), installs the',
                    'binary to `/usr/bin/wedge`, the configuration to `/etc/wedge/` (root:wedge,',
                    'mode 0750/0640) and the systemd unit. Upgrades keep your configuration.', ''
            }
            $md += '## 4. Configure', '',
                'The default configuration serves a test page on `127.0.0.1:8080` only. Edit',
                '`/etc/wedge/wedge.toml` (see the [configuration reference](../guide/configuration.md)),',
                'then check it:', '',
                (Get-Block 'sudo wedge check-config -c /etc/wedge/wedge.toml'), ''
            $md += '## 5. Start', '', (Get-Block $p.start), ''
            $md += '## 6. Check', '', (Get-Block 'curl -I http://127.0.0.1:8080/'), '',
                'Expect `HTTP/1.1 200 OK` and an `x-content-type-options: nosniff` header.', ''
            $md += '## Reload after configuration changes', '', (Get-Block $p.reload), ''
            $md += '## Remove', '', (Get-Block $p.remove), ''
        }
        'windows' {
            $msi = $asset.Replace('${VERSION}', $version)
            $zip = "wedge-$version-x86_64-pc-windows-msvc.zip"
            $rel = $base.Replace('$VERSION', $version)
            $md += '## 1. Download and verify', '',
                'Download from the browser:', '',
                "- Installer: [$msi]($rel/$msi)",
                "- Portable zip, no installer: [$zip]($rel/$zip) (see [below](#portable-zip-no-installer))",
                "- Checksums: [SHA256SUMS]($rel/SHA256SUMS)",
                "- All files and signatures: the [v$version release page]($($rel.Replace('/releases/download/', '/releases/tag/')))", '',
                'Then compare `Get-FileHash <file>` with the file''s line in `SHA256SUMS`.', '',
                'Or download and verify in PowerShell:', '', (Get-PsBlock @(
                    "`$BASE = `"$rel`""
                    "Invoke-WebRequest `"`$BASE/$msi`" -OutFile $msi"
                    "Invoke-WebRequest `"`$BASE/SHA256SUMS`" -OutFile SHA256SUMS"
                    "`$expected = (Select-String SHA256SUMS -Pattern ' $msi`$').Line.Split(' ')[0]"
                    "if ((Get-FileHash $msi -Algorithm SHA256).Hash.ToLower() -ne `$expected) { throw 'checksum mismatch' }"
                )), ''
            $md += '## 2. Install', '',
                "Double-click ``$msi``, or from an elevated PowerShell (``/qn`` for a silent install):", '',
                (Get-PsBlock @("msiexec /i $msi")), '',
                'The installer:', '',
                '- installs `wedge.exe`, the user guide and examples to `C:\Program Files\wedge` and',
                '  adds it to `PATH`;',
                '- creates `C:\ProgramData\wedge\wedge.toml` (loopback only, port 8080) and a test',
                '  page; upgrades and uninstall keep them;',
                '- registers and starts the `wedge` service as the virtual account `NT SERVICE\wedge`,',
                '  logging to `C:\ProgramData\wedge\logs\wedge.log`.', '',
                'Until the installer is Authenticode-signed (pending SignPath Foundation approval),',
                'Windows SmartScreen reports an unknown publisher; check the SHA-256 above first.', ''
            $md += '## 3. Check', '', (Get-PsBlock @('curl.exe -I http://127.0.0.1:8080/')), ''
            $md += '## Configure and reload', '', (Get-PsBlock @(
                    'notepad C:\ProgramData\wedge\wedge.toml'
                    'wedge check-config -c C:\ProgramData\wedge\wedge.toml'
                    'sc.exe control wedge paramchange'
                )), '',
                'To serve the network, change `listen` (for example `"0.0.0.0:80"`) and allow the',
                'port in Windows Defender Firewall.', ''
            $md += '## Remove', '',
                "Settings > Apps > wEdge > Uninstall, or ``msiexec /x $msi``. The configuration in",
                '`C:\ProgramData\wedge` is kept.', ''
            $md += '## Portable zip (no installer)', '',
                "[$zip]($rel/$zip) contains the same files. Copy",
                '`wedge.exe` to `C:\Program Files\wedge\` (the service refuses other locations),',
                'then from an elevated PowerShell:', '', (Get-PsBlock @(
                    "& 'C:\Program Files\wedge\wedge.exe' service install -c C:\ProgramData\wedge\wedge.toml"
                    'Start-Service wedge'
                )), ''
        }
        'macos' {
            $md += '## 1. Download and verify', '',
                'Use `aarch64-apple-darwin` on Apple silicon and `x86_64-apple-darwin` on Intel Macs.', '',
                (Get-Block "VERSION=$version`nBASE=$base`ncurl -fLO `"`$BASE/$asset`"`ncurl -fLO `"`$BASE/SHA256SUMS`"`ngrep `" $asset`$`" SHA256SUMS | shasum -a 256 -c -"), ''
            $md += '## 2. Install and run', '',
                (Get-Block "tar -xzf $asset`nsudo install -m 0755 aarch64-apple-darwin/wedge /usr/local/bin/wedge`ncd aarch64-apple-darwin/examples && wedge run -c wedge.toml"), '',
                'The binary is not notarized; if Gatekeeper blocks it, allow it in',
                'System Settings > Privacy & Security.', ''
        }
    }
    $file = "docs/install/$($p.id).md"
    [IO.File]::WriteAllText((Join-Path $PWD $file), (($md -join "`n").TrimEnd() + "`n"))
    $pages += [pscustomobject]@{ Title = $p.title; File = "$($p.id).md"; Status = if ($p.tested -eq 'ci-runner') { 'Untested (MSI tested in CI)' } else { (Get-Status $p).Split(' ')[0].TrimEnd(':').TrimEnd('.') } }
}

$index = @($header, '# Installing wedge', '',
    'Pick your platform. Every Linux guide is run in a clean container before a release',
    '(`scripts/test-install.ps1`); Windows and macOS guides stay marked "untested" until',
    'they have been run on a real machine.', '',
    '| Platform | Guide | Status |', '|---|---|---|')
$index += $pages | ForEach-Object { "| $($_.Title) | [$($_.File)]($($_.File)) | $($_.Status) |" }
$index += '', 'Other Linux distributions: use the static `x86_64-unknown-linux-musl` or',
    '`aarch64-unknown-linux-musl` tarball and follow the Alpine guide.'
[IO.File]::WriteAllText((Join-Path $PWD 'docs/install/README.md'), ($index -join "`n") + "`n")
Write-Host "wrote $($pages.Count) guides and docs/install/README.md"
