# Writes docs/guide/configuration-reference.md from the configuration JSON
# Schema (`wedge schema`), so every key, type, default and limit in the
# reference matches the code. Run after changing the configuration model.
#
# Usage: pwsh scripts/gen-config-reference.ps1
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path $PSScriptRoot -Parent)

$schema = (cargo run -q -p wedge -- schema) -join "`n" | ConvertFrom-Json
if ($LASTEXITCODE -ne 0) { throw 'wedge schema failed' }
$defs = $schema.'$defs'
# Types shown as values rather than as tables of their own.
$scalarDefs = @{
    SecretRef  = 'secret reference: `"env:NAME"` or `"file:/path"`'
    IpNet      = 'IP address or CIDR range'
    TlsVersion = '`"1.2"` or `"1.3"`'
}

function Get-RefName($node) {
    if ($node.'$ref') { return $node.'$ref'.Split('/')[-1] }
    if ($node.anyOf) {
        foreach ($alt in $node.anyOf) { if ($alt.'$ref') { return $alt.'$ref'.Split('/')[-1] } }
    }
    $null
}

function Get-TypeText($node) {
    $ref = Get-RefName $node
    if ($ref -and $scalarDefs.ContainsKey($ref)) { return $scalarDefs[$ref] }
    if ($ref) { return "table (see below)" }
    switch ($node.type) {
        'integer' {
            $range = if ($null -ne $node.minimum -and $null -ne $node.maximum) { " ($($node.minimum) to $($node.maximum))" } else { '' }
            return "integer$range"
        }
        'boolean' { return 'boolean' }
        'string' { return 'string' }
        'array' {
            $item = Get-TypeText $node.items
            return "list of $item"
        }
        'object' {
            if ($node.additionalProperties) { return 'table of name = string' }
            return 'table'
        }
    }
    if ($node.type -is [array]) { return ($node.type | Where-Object { $_ -ne 'null' }) -join ' or ' }
    'value'
}

function Get-DefaultText($node) {
    if ($null -eq $node.PSObject.Properties['default']) { return '' }
    $value = $node.default
    if ($null -eq $value) { return 'unset' }
    if ($value -is [bool]) { return "``$("$value".ToLower())``" }
    if ($value -is [array] -and $value.Count -eq 0) { return '`[]`' }
    if ($value -is [string]) { return "``""$value""``" }
    if ($value -is [pscustomobject]) { return '' }
    "``$(($value | ConvertTo-Json -Compress -Depth 4))``"
}

function Get-Text([string]$s) { ($s -replace '\s*\n\s*', ' ').Trim() }

$out = [System.Collections.Generic.List[string]]::new()
$queue = [System.Collections.Generic.List[object]]::new()

function Add-Table([string]$title, $def, [string]$summary) {
    $out.Add("## ``$title``")
    $out.Add('')
    if ($summary) { $out.Add((Get-Text $summary)); $out.Add('') }
    $out.Add('| Key | Type | Default | Description |')
    $out.Add('|---|---|---|---|')
    $required = @($def.required)
    foreach ($prop in $def.properties.PSObject.Properties) {
        $node = $prop.Value
        $default = Get-DefaultText $node
        if (-not $default -and $prop.Name -in $required) { $default = '**required**' }
        $desc = Get-Text $node.description
        $out.Add("| ``$($prop.Name)`` | $(Get-TypeText $node) | $default | $desc |")
        $ref = Get-RefName $node
        if (-not $ref -and $node.type -eq 'array') { $ref = Get-RefName $node.items; $isArray = $true } else { $isArray = $false }
        if ($ref -and -not $scalarDefs.ContainsKey($ref)) {
            $child = if ($isArray) { "[[$($title.Trim('[]')).$($prop.Name)]]" } else { "[$($title.Trim('[]')).$($prop.Name)]" }
            $queue.Add(@($child, $ref, $desc))
        }
    }
    $out.Add('')
}

$out.Add('<!-- SPDX-License-Identifier: Apache-2.0 -->')
$out.Add('<!-- Copyright (c) Alingan Patra -->')
$out.Add('<!-- Generated by scripts/gen-config-reference.ps1 from `wedge schema`. Do not edit. -->')
$out.Add('# Configuration reference')
$out.Add('')
$out.Add('Every key wedge accepts, generated from the JSON Schema that wedge validates')
$out.Add('against (print it with `wedge schema`). Unknown keys are rejected, so a typo is')
$out.Add('an error rather than a silently ignored setting. For explanations and worked')
$out.Add('examples, see the [user guide](README.md).')
$out.Add('')

# Top level, then breadth-first through nested tables.
$queue.Add(@('[server]', 'ServerConfig', 'Process-wide settings.'))
$queue.Add(@('[[upstream]]', 'Upstream', $defs.Upstream.description))
$queue.Add(@('[[vhost]]', 'VirtualHost', $defs.VirtualHost.description))
for ($i = 0; $i -lt $queue.Count; $i++) {
    $title, $ref, $summary = $queue[$i]
    $def = $defs.$ref
    $text = if ($def.description) { $def.description } else { $summary }
    Add-Table $title $def $text
}

[IO.File]::WriteAllText((Join-Path $PWD 'docs/guide/configuration-reference.md'), ($out -join "`n").TrimEnd() + "`n")
Write-Host "wrote docs/guide/configuration-reference.md ($($queue.Count) tables)"
